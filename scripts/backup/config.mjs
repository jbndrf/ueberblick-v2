// Generates litestream.yml from the databases found in a data directory (control.db + project-<key>.db).
// Discovery, not a hand-kept list: a new project database is picked up the next time the config is generated.
import { readdirSync, statSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

const PROJECT_DB = /^project-[a-z0-9_-]+\.db$/;

/** File names of every database in `dir`, control.db first, then project databases sorted. */
export function discoverDatabases(dir) {
  const files = readdirSync(dir).filter((f) => statSync(join(dir, f)).isFile());
  if (!files.includes('control.db')) throw new Error(`no control.db in ${dir}`);
  return ['control.db', ...files.filter((f) => PROJECT_DB.test(f)).sort()];
}

/** Replica URL of one database under a base URL (file:///dir, s3://bucket/prefix, ...). */
export function replicaUrl(base, dbFile) {
  return `${base.replace(/\/+$/, '')}/${basename(dbFile)}`;
}

/**
 * Replica retention: 30 days. needs-owner: legal sign-off on the maximum time erased personal data may survive in a
 * backup (docs/decisions/later/B-005-gdpr-erasure-redaction-first.md). A restore replays the erasure journal on top.
 */
export const DEFAULT_RETENTION = '720h';

/** Renders litestream.yml. `replicaBase` is a Litestream replica URL prefix; each database gets its own path below it. */
export function renderConfig({
  dataDir,
  replicaBase,
  databases,
  syncInterval = '1s',
  retention = DEFAULT_RETENTION,
}) {
  const lines = [
    '# Generated by scripts/backup/config.mjs. Do not edit; regenerate when a project is added.',
    `# retention ${retention}: needs-owner (legal sign-off on the maximum life of erased data in a backup).`,
    'dbs:',
  ];
  for (const db of databases) {
    lines.push(`  - path: ${join(resolve(dataDir), db)}`);
    lines.push('    replicas:');
    lines.push(`      - url: ${replicaUrl(replicaBase, db)}`);
    lines.push(`        sync-interval: ${syncInterval}`);
    lines.push(`        retention: ${retention}`);
  }
  return lines.join('\n') + '\n';
}

/** Discovers the databases in `dataDir` and renders the config. */
export function generateConfig({ dataDir, replicaBase, ...rest }) {
  return renderConfig({ dataDir, replicaBase, databases: discoverDatabases(dataDir), ...rest });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [dataDir, replicaBase] = process.argv.slice(2);
  if (!dataDir || !replicaBase) {
    console.error(
      'usage: node scripts/backup/config.mjs <data-dir> <replica-base-url> > ops/litestream/litestream.yml',
    );
    process.exit(2);
  }
  process.stdout.write(generateConfig({ dataDir, replicaBase }));
}
